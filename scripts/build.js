#!/usr/bin/env node
// Bundles src/*.js into a single userscript: dist/stockfish-overlay.user.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkg = require(path.join(root, 'package.json'));
const ORDER = ['chess.js', 'board.js', 'engine.js', 'overlay.js', 'settings.js', 'panel.js', 'main.js'];

const header = `// ==UserScript==
// @name         Stockfish Overlay for Chess.com Bot Games
// @namespace    https://github.com/arch0zn-domain/chess-bot
// @version      ${pkg.version}
// @description  Local Stockfish 19 (WebAssembly) analysis panel, eval bar and best-move arrows for Chess.com "Play vs Computer" and Analysis. Works on iPhone via the Userscripts Safari extension.
// @author       chess-bot
// @match        https://www.chess.com/*
// @match        https://chess.com/*
// @run-at       document-idle
// @grant        none
// @inject-into  auto
// @noframes
// ==/UserScript==
`;

let body = '';
for (const file of ORDER) {
  const src = fs.readFileSync(path.join(root, 'src', file), 'utf8')
    .split('\n')
    .filter((line) => !line.includes('// @node-only'))
    .join('\n');
  body += `\n// ===== ${file} =====\n${src.trim()}\n`;
}

const out = `${header}\n/* Generated by scripts/build.js from src/ — edit the sources, not this file. */\n(function () {\n'use strict';\n${body}})();\n`;
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const dest = path.join(root, 'dist', 'stockfish-overlay.user.js');
fs.writeFileSync(dest, out);
console.log('Wrote ' + path.relative(root, dest) + ' (' + (out.length / 1024).toFixed(1) + ' KB)');
